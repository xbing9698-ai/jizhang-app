export function classify(t, memory = {}) {
  // 1. 商户记忆优先
  if (t.counterparty && memory[t.counterparty]) return memory[t.counterparty];
  // 2. 支付宝原始分类映射
  if (t.source === '支付宝' && ALIPAY_CATEGORY_MAP[t.rawCategory])
    return ALIPAY_CATEGORY_MAP[t.rawCategory];
  // 3. 关键词规则
  const hay = `${t.counterparty} ${t.description}`;
  for (const [cat, words] of KEYWORD_RULES)
    if (words.some(w => hay.includes(w))) return cat;
  // 4. 兜底
  return '其他';
}

// 解析交易的最终分类：手动指定 > 规则推断。
// t.manual === true 表示用户手动改过，其 myCategory 绝对优先、永不被规则覆盖
// （修复：商户名为空/"/"等情况下，重载后手动分类被规则重算覆盖而丢失）。
export function resolveCategory(t, memory = {}) {
  if (t.manual && t.myCategory) return t.myCategory;
  return classify(t, memory);
}
